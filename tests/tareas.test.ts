import { describe, expect, it } from "vitest";
import { ErrorTareas, configuracion, tareasGitHub, validarCambio, validarTarea } from "../src/tareas/github";

// Un GitHub de mentira: guarda incidencias y comentarios en memoria y apunta cada llamada.
function githubFalso() {
  const incidencias: Record<number, { number: number; title: string; body: string; state: string; created_at: string; comments: number; labels: { name: string }[]; pull_request?: object }> = {
    7: { number: 7, title: "Un PR", body: "", state: "open", created_at: "2026-11-01T00:00:00Z", comments: 0, labels: [{ name: "tarea" }], pull_request: {} },
    8: { number: 8, title: "Incidencia ajena", body: "", state: "open", created_at: "2026-11-01T00:00:00Z", comments: 0, labels: [] },
  };
  const comentarios: Record<number, { id: number; body: string; created_at: string }[]> = {};
  const llamadas: string[] = [];
  let siguiente = 20;
  const pedir = (async (url: string | URL | Request, init?: RequestInit) => {
    const ruta = String(url).replace("https://api.github.com/repos/a/b", "");
    const metodo = init?.method ?? "GET";
    llamadas.push(`${metodo} ${ruta.split("?")[0]}`);
    if ((init?.headers as Record<string, string>).authorization !== "Bearer bueno") return new Response("{}", { status: 401 });
    const cuerpo = init?.body ? JSON.parse(String(init.body)) : {};
    const json = (v: unknown, status = 200) => new Response(JSON.stringify(v), { status });
    const m = ruta.match(/^\/issues\/(\d+)(\/comments)?/);
    if (ruta.startsWith("/issues?")) return json(Object.values(incidencias).filter((i) => i.labels.some((l) => l.name === "tarea")));
    if (ruta === "/issues" && metodo === "POST") {
      const n = siguiente++;
      incidencias[n] = { number: n, title: cuerpo.title, body: cuerpo.body, state: "open", created_at: "2026-11-16T10:00:00Z", comments: 0, labels: cuerpo.labels.map((name: string) => ({ name })) };
      return json(incidencias[n], 201);
    }
    if (!m || !incidencias[Number(m[1])]) return json({}, 404);
    const i = incidencias[Number(m[1])];
    if (m[2] && metodo === "POST") {
      const c = { id: siguiente++, body: cuerpo.body, created_at: "2026-11-16T11:00:00Z" };
      (comentarios[i.number] ??= []).push(c);
      i.comments += 1;
      return json(c, 201);
    }
    if (m[2]) return json(comentarios[i.number] ?? []);
    if (metodo === "PATCH") i.state = cuerpo.state;
    return json(i);
  }) as typeof fetch;
  return { pedir, incidencias, comentarios, llamadas };
}

describe("tareas guardadas como incidencias", () => {
  it("sin permiso configurado no hay tareas, y el repositorio debe tener forma de repositorio", () => {
    expect(configuracion({})).toBeNull();
    expect(configuracion({ GRADIOX_GITHUB_TOKEN: "x" })?.repo).toBe("victorhugocamposvazquez/gradiox-app");
    expect(configuracion({ GRADIOX_GITHUB_TOKEN: "x", GRADIOX_GITHUB_REPO: "../otra cosa" })).toBeNull();
  });

  it("crea una tarea con su etiqueta, la lista sin los PR y no enseña la marca interna", async () => {
    const g = githubFalso();
    const t = tareasGitHub({ token: "bueno", repo: "a/b" }, g.pedir);
    const nueva = await t.crear("  Falta el gasto del mes ", "En la pantalla de Luz");
    expect(nueva).toMatchObject({ titulo: "Falta el gasto del mes", detalle: "En la pantalla de Luz", abierta: true, deLaApp: true });
    expect(g.incidencias[nueva.numero].labels).toEqual([{ name: "tarea" }]);
    expect((await t.listar()).map((x) => x.numero)).toEqual([nueva.numero]);
  });

  it("distingue las notas escritas en la app de las respuestas y quita el pie de las respuestas", async () => {
    const g = githubFalso();
    const t = tareasGitHub({ token: "bueno", repo: "a/b" }, g.pedir);
    const { numero } = await t.crear("Una tarea", "");
    await t.anotar(numero, "¿Cuándo estará?");
    g.comentarios[numero].push({ id: 99, body: "Esta semana.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_", created_at: "2026-11-16T12:00:00Z" });
    expect((await t.notas(numero)).map((n) => [n.autor, n.texto])).toEqual([["app", "¿Cuándo estará?"], ["equipo", "Esta semana."]]);
  });

  it("marca como hecha y vuelve a abrir", async () => {
    const g = githubFalso();
    const t = tareasGitHub({ token: "bueno", repo: "a/b" }, g.pedir);
    const { numero } = await t.crear("Una tarea", "");
    expect((await t.marcar(numero, false)).abierta).toBe(false);
    expect((await t.marcar(numero, true)).abierta).toBe(true);
  });

  it("no deja tocar incidencias que no son tareas, ni PR", async () => {
    const g = githubFalso();
    const t = tareasGitHub({ token: "bueno", repo: "a/b" }, g.pedir);
    for (const n of [7, 8, 404]) {
      await expect(t.anotar(n, "hola")).rejects.toMatchObject({ estado: 404 });
      await expect(t.marcar(n, false)).rejects.toMatchObject({ estado: 404 });
    }
    expect(g.llamadas.some((l) => l.startsWith("POST") || l.startsWith("PATCH"))).toBe(false);
  });

  it("explica cuando GitHub rechaza el permiso", async () => {
    const g = githubFalso();
    await expect(tareasGitHub({ token: "malo", repo: "a/b" }, g.pedir).listar()).rejects.toThrow(ErrorTareas);
  });

  it("valida lo que llega de la pantalla", () => {
    expect(validarTarea({ titulo: " Hola " })).toEqual({ titulo: "Hola", detalle: "" });
    expect(validarTarea({ titulo: "" })).toHaveProperty("error");
    expect(validarTarea({ titulo: "x".repeat(161) })).toHaveProperty("error");
    expect(validarTarea({ titulo: "a", detalle: 3 })).toHaveProperty("error");
    expect(validarCambio({ abierta: false })).toEqual({ abierta: false });
    expect(validarCambio({ nota: " ok " })).toEqual({ nota: "ok" });
    expect(validarCambio({})).toHaveProperty("error");
  });
});
