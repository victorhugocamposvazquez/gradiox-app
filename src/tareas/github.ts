// Las tareas de Gradiox se guardan como incidencias de GitHub con la etiqueta
// «tarea». Así las ve y las contesta quien trabaja en el repositorio, y la app
// enseña sus respuestas. No hace falta base de datos.

export type Nota = { id: number; texto: string; autor: "app" | "equipo"; cuando: string };
export type TareaApp = { numero: number; titulo: string; detalle: string; abierta: boolean; creada: string; notas: number; deLaApp: boolean };

export const ETIQUETA = "tarea";
export const MAX_TITULO = 160;
export const MAX_TEXTO = 4000;
// Lo escrito desde la app lleva esta marca invisible, para distinguirlo de las respuestas.
const MARCA = "<!-- gradiox-app -->";
const PIE = /\n*---\n_Generated by \[Claude Code\]\([^)]*\)_\s*$/;

export type Configuracion = { token: string; repo: string };
export function configuracion(entorno: Record<string, string | undefined> = process.env): Configuracion | null {
  const token = entorno.GRADIOX_GITHUB_TOKEN;
  const repo = entorno.GRADIOX_GITHUB_REPO || "victorhugocamposvazquez/gradiox-app";
  return token && /^[\w.-]+\/[\w.-]+$/.test(repo) ? { token, repo } : null;
}

export class ErrorTareas extends Error {
  constructor(mensaje: string, readonly estado = 502) {
    super(mensaje);
  }
}

const limpiar = (texto: string | null | undefined) => (texto ?? "").replace(MARCA, "").replace(PIE, "").trim();
const autor = (texto: string | null | undefined): Nota["autor"] => ((texto ?? "").includes(MARCA) ? "app" : "equipo");
const firmar = (texto: string) => `${texto.trim()}\n\n${MARCA}`;

type Incidencia = { number: number; title: string; body: string | null; state: string; created_at: string; comments: number; pull_request?: unknown };
type Comentario = { id: number; body: string | null; created_at: string };

export function tareasGitHub(c: Configuracion, pedir: typeof fetch = fetch) {
  const llamar = async <T>(ruta: string, opciones: { metodo?: string; cuerpo?: unknown } = {}): Promise<T> => {
    let r: Response;
    try {
      r = await pedir(`https://api.github.com/repos/${c.repo}${ruta}`, {
        method: opciones.metodo ?? "GET",
        headers: { authorization: `Bearer ${c.token}`, accept: "application/vnd.github+json", "x-github-api-version": "2022-11-28", "user-agent": "gradiox-app", ...(opciones.cuerpo ? { "content-type": "application/json" } : {}) },
        body: opciones.cuerpo ? JSON.stringify(opciones.cuerpo) : undefined,
        cache: "no-store",
      });
    } catch {
      throw new ErrorTareas("No se ha podido hablar con GitHub");
    }
    if (r.status === 401 || r.status === 403) throw new ErrorTareas("GitHub no acepta el permiso configurado en el servidor");
    if (r.status === 404) throw new ErrorTareas("Esa tarea no existe", 404);
    if (!r.ok) throw new ErrorTareas(`GitHub ha respondido ${r.status}`);
    return (await r.json()) as T;
  };
  const tarea = (i: Incidencia): TareaApp => ({ numero: i.number, titulo: i.title, detalle: limpiar(i.body), abierta: i.state === "open", creada: i.created_at, notas: i.comments, deLaApp: autor(i.body) === "app" });
  /** Solo se tocan incidencias con la etiqueta de tareas: la app no puede cambiar otras. */
  const esTarea = async (numero: number) => {
    const i = await llamar<Incidencia & { labels: { name: string }[] }>(`/issues/${numero}`);
    if (i.pull_request || !i.labels.some((l) => l.name === ETIQUETA)) throw new ErrorTareas("Esa tarea no existe", 404);
    return i;
  };

  return {
    async listar(): Promise<TareaApp[]> {
      const todas = await llamar<Incidencia[]>(`/issues?labels=${ETIQUETA}&state=all&per_page=100&sort=created&direction=desc`);
      return todas.filter((i) => !i.pull_request).map(tarea);
    },
    async crear(titulo: string, detalle: string): Promise<TareaApp> {
      return tarea(await llamar<Incidencia>("/issues", { metodo: "POST", cuerpo: { title: titulo.trim(), body: firmar(detalle), labels: [ETIQUETA] } }));
    },
    async notas(numero: number): Promise<Nota[]> {
      await esTarea(numero);
      const lista = await llamar<Comentario[]>(`/issues/${numero}/comments?per_page=100`);
      return lista.map((n) => ({ id: n.id, texto: limpiar(n.body), autor: autor(n.body), cuando: n.created_at }));
    },
    async anotar(numero: number, texto: string): Promise<Nota> {
      await esTarea(numero);
      const n = await llamar<Comentario>(`/issues/${numero}/comments`, { metodo: "POST", cuerpo: { body: firmar(texto) } });
      return { id: n.id, texto: limpiar(n.body), autor: "app", cuando: n.created_at };
    },
    async marcar(numero: number, abierta: boolean): Promise<TareaApp> {
      await esTarea(numero);
      return tarea(await llamar<Incidencia>(`/issues/${numero}`, { metodo: "PATCH", cuerpo: { state: abierta ? "open" : "closed" } }));
    },
  };
}

const texto = (v: unknown, max: number, obligatorio: boolean): string | null => {
  if (v === undefined || v === null) return obligatorio ? null : "";
  if (typeof v !== "string") return null;
  const t = v.trim();
  return t.length > max || (obligatorio && !t) ? null : t;
};

/** Comprueba lo que manda la pantalla al crear una tarea. */
export function validarTarea(cuerpo: unknown): { titulo: string; detalle: string } | { error: string } {
  const c = (typeof cuerpo === "object" && cuerpo !== null ? cuerpo : {}) as Record<string, unknown>;
  const titulo = texto(c.titulo, MAX_TITULO, true);
  if (titulo === null) return { error: `La tarea necesita un título de hasta ${MAX_TITULO} letras` };
  const detalle = texto(c.detalle, MAX_TEXTO, false);
  if (detalle === null) return { error: "El detalle es demasiado largo" };
  return { titulo, detalle };
}

/** Comprueba un cambio sobre una tarea: una nota nueva o marcarla como hecha o abierta. */
export function validarCambio(cuerpo: unknown): { nota: string } | { abierta: boolean } | { error: string } {
  const c = (typeof cuerpo === "object" && cuerpo !== null ? cuerpo : {}) as Record<string, unknown>;
  if (typeof c.abierta === "boolean") return { abierta: c.abierta };
  const nota = texto(c.nota, MAX_TEXTO, true);
  return nota === null ? { error: "La nota está vacía o es demasiado larga" } : { nota };
}
